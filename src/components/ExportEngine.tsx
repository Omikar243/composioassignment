import React, { useState } from "react";
import {
  FileText,
  FileCode,
  Download,
  Copy,
  Check,
  Share2,
} from "lucide-react";
import { IntegrationReadinessGuide, ClaimEvidence } from "../types/guide";

export interface ExportEngineProps {
  guide: IntegrationReadinessGuide;
}

/**
 * Format ClaimEvidence to clean inline markdown text
 */
function formatEvidenceTag(e: ClaimEvidence): string {
  const markdownLink = (label: string, url: string) => {
    const safeLabel = label
      .replaceAll("\\", "\\\\")
      .replaceAll("[", "\\[")
      .replaceAll("]", "\\]");
    const safeUrl = url.replace(/[\s<>]/g, (character) => encodeURIComponent(character));
    return `[${safeLabel}](<${safeUrl}>)`;
  };

  switch (e.kind) {
    case "tested_live":
      return e.referenceUrl
        ? markdownLink(`Tested Live: ${e.testedAt}`, e.referenceUrl)
        : `\`[Tested Live: ${e.testedAt}]\``;
    case "documented_not_tested":
      return markdownLink(`Documented: ${e.sourceTitle}`, e.sourceUrl);
    case "unverified_hypothesis": {
      const tag = `\`[Hypothesis: ${e.hypothesisBasis}]\``;
      return e.relatedSourceUrl
        ? `${tag} (${markdownLink("Related source", e.relatedSourceUrl)})`
        : tag;
    }
  }
}

/**
 * Generates an exhaustive, high-craft Markdown runbook from an IntegrationReadinessGuide.
 */
export function generateGuideMarkdown(guide: IntegrationReadinessGuide): string {
  const timestamp = new Date().toISOString();
  let md = `# ${guide.appName} — Composio Integration & OAuth Readiness Runbook\n\n`;
  md += `> Generated by APM Integrations OAuth Readiness Copilot on ${timestamp}\n`;
  md += `> Official Website: ${guide.websiteUrl}\n`;
  if (guide.composioToolkitSlug) {
    md += `> Composio Toolkit Slug: \`${guide.composioToolkitSlug}\`\n`;
  }
  md += `\n---\n\n`;

  // 1. Executive Readiness Summary
  md += `## 1. Executive Readiness & Timeline Summary\n\n`;
  md += `| Attribute | Value | Epistemic Evidence Status |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **Auth Path Model** | \`${guide.readinessSummary.authPathClassification}\` | System Classification |\n`;
  md += `| **Active Setup Duration** | ${guide.readinessSummary.activeSetupTime.value} | ${formatEvidenceTag(guide.readinessSummary.activeSetupTime.evidence)} |\n`;
  md += `| **Approval Wait Duration** | ${guide.readinessSummary.approvalWaitTime.value} | ${formatEvidenceTag(guide.readinessSummary.approvalWaitTime.evidence)} |\n`;
  md += `| **Composio Managed Auth** | \`${guide.composioManagedAuthStatus.value}\` | ${formatEvidenceTag(guide.composioManagedAuthStatus.evidence)} |\n`;
  md += `| **Supported Schemes** | ${guide.supportedAuthSchemes.value.join(", ")} | ${formatEvidenceTag(guide.supportedAuthSchemes.evidence)} |\n\n`;
  md += `**Readiness Banner:**\n> ${guide.readinessSummary.oauthNecessityBanner}\n\n`;
  md += `**Summary:** ${guide.readinessSummary.oneLineSummary}\n\n`;

  // 2. Prerequisites
  md += `## 2. Prerequisites Checklist\n\n`;
  const prereqs = Array.isArray(guide.prerequisites)
    ? guide.prerequisites
    : guide.prerequisites.value;

  if (Array.isArray(prereqs)) {
    prereqs.forEach((item: any, i: number) => {
      const p = item.value || item;
      const testReq = p.requiredForTesting ? "[X] Required for Dev" : "[ ] Optional for Dev";
      const prodReq = p.requiredForProduction ? "[X] Required for Prod" : "[ ] Optional for Prod";
      md += `${i + 1}. **${p.item}** (${testReq} | ${prodReq})\n`;
      md += `   - ${p.detail}\n`;
    });
    md += `\n`;
  }

  // 3. Technical Specification
  md += `## 3. Technical Authentication Specification\n\n`;

  if (guide.authSpec.mode === "oauth") {
    const o = guide.authSpec;
    md += `### Zone A: Provider-Owned OAuth Endpoints (Do NOT paste as Redirect URI)\n\n`;
    md += `- **Authorization URL**: \`${o.providerEndpoints.authorizationUrl.value}\` ${formatEvidenceTag(o.providerEndpoints.authorizationUrl.evidence)}\n`;
    md += `- **Token URL**: \`${o.providerEndpoints.tokenUrl.value}\` ${formatEvidenceTag(o.providerEndpoints.tokenUrl.evidence)}\n`;
    if (o.providerEndpoints.revocationUrl) {
      md += `- **Revocation URL**: \`${o.providerEndpoints.revocationUrl.value}\` ${formatEvidenceTag(o.providerEndpoints.revocationUrl.evidence)}\n`;
    }
    if (o.providerEndpoints.userInfoUrl) {
      md += `- **UserInfo URL**: \`${o.providerEndpoints.userInfoUrl.value}\` ${formatEvidenceTag(o.providerEndpoints.userInfoUrl.evidence)}\n`;
    }
    md += `- **PKCE Requirement**: \`${o.pkceRequired.value}\` ${formatEvidenceTag(o.pkceRequired.evidence)}\n`;
    md += `- **Token & Refresh Behavior**: ${o.tokenAndRefreshBehavior.value} ${formatEvidenceTag(o.tokenAndRefreshBehavior.evidence)}\n\n`;

    md += `### Zone B: Composio Callback Guidance (Configure in Provider Portal)\n\n`;
    if (o.composioCallbackGuidance.activeConfigCallbackUri) {
      md += `- **Active Config Callback URI**: \`${o.composioCallbackGuidance.activeConfigCallbackUri.value}\`\n`;
    }
    md += `- **How to Locate in Composio**: ${o.composioCallbackGuidance.howToLocateAndVerify}\n`;
    md += `- **Reference Note**: ${o.composioCallbackGuidance.documentedReferenceNote.value} ${formatEvidenceTag(o.composioCallbackGuidance.documentedReferenceNote.evidence)}\n\n`;

    md += `### Required Scopes\n\n`;
    md += `| Scope | Category | Description | Sensitive? |\n`;
    md += `| :--- | :--- | :--- | :--- |\n`;
    o.scopes.value.forEach((s) => {
      md += `| \`${s.scope}\` | ${s.category} | ${s.description} | ${s.isSensitiveOrRestricted ? "⚠️ Yes" : "No"} |\n`;
    });
    md += `\n`;
  } else if (guide.authSpec.mode === "direct_credential") {
    const d = guide.authSpec;
    md += `### Direct Credential Specification (Zero OAuth Endpoints)\n\n`;
    md += `> **Notice**: ${d.whyOAuthIsNotRequired}\n\n`;
    md += `- **Credential Label**: ${d.credentialLabel}\n`;
    md += `- **Scheme**: \`${d.scheme}\`\n`;
    md += `- **Format**: \`${d.headerOrParamFormat.value}\` ${formatEvidenceTag(d.headerOrParamFormat.evidence)}\n`;
    md += `- **Rotation Rules**: ${d.rotationAndExpiryRules.value} ${formatEvidenceTag(d.rotationAndExpiryRules.evidence)}\n`;
    if (d.portalUrl) {
      md += `- **Key Generation Portal**: ${d.portalUrl}\n`;
    }
    md += `\n`;
  } else if (guide.authSpec.mode === "hybrid") {
    const h = guide.authSpec;
    md += `### Hybrid Auth Specification\n\n`;
    md += `**Path Decision Guide:**\n${h.pathDecisionGuide.value}\n\n`;
    md += `#### Option 1: Direct Token Path (Internal/Single-Workspace)\n`;
    md += `- **Credential**: ${h.directCredentialPath.credentialLabel} (\`${h.directCredentialPath.scheme}\`)\n`;
    md += `- **Format**: \`${h.directCredentialPath.headerOrParamFormat.value}\`\n\n`;
    md += `#### Option 2: Public OAuth 2.0 Path (Multi-Tenant)\n`;
    md += `- **Authorization URL**: \`${h.oauthPath.providerEndpoints.authorizationUrl.value}\`\n`;
    md += `- **Token URL**: \`${h.oauthPath.providerEndpoints.tokenUrl.value}\`\n\n`;
  }

  // 4. Setup Runbook
  md += `## 4. Step-by-Step Setup Runbook\n\n`;
  guide.setupRunbook.forEach((step) => {
    md += `### Step ${step.stepNumber}: ${step.title}\n`;
    md += `- **Actor**: \`${step.actor}\`\n`;
    md += `- **Estimated Duration**: ${step.estimatedDuration.value} ${formatEvidenceTag(step.estimatedDuration.evidence)}\n`;
    if (step.portalUrl) {
      md += `- **Portal URL**: ${step.portalUrl}\n`;
    }
    md += `\n**Instructions:**\n`;
    step.instructions.forEach((ins) => {
      md += `1. ${ins}\n`;
    });
    if (step.copyableAssets && step.copyableAssets.length > 0) {
      md += `\n**Copyable Assets:**\n`;
      step.copyableAssets.forEach((asset) => {
        md += `- **${asset.label}**: \`${asset.value}\` (${asset.note})\n`;
      });
    }
    if (step.commonPitfall) {
      md += `\n> ⚠️ **Common Pitfall**: ${step.commonPitfall.value} ${formatEvidenceTag(step.commonPitfall.evidence)}\n`;
    }
    md += `\n`;
  });

  // 5. Blockers & Error Playbooks
  md += `## 5. Blockers & Troubleshooting Playbooks\n\n`;
  const blockers = Array.isArray(guide.blockersAndPlaybooks)
    ? guide.blockersAndPlaybooks
    : guide.blockersAndPlaybooks.value;

  if (Array.isArray(blockers)) {
    blockers.forEach((b: any, idx: number) => {
      const item = b.value || b;
      md += `### ${idx + 1}. ${item.blockerTitle}\n`;
      if (item.errorCodeOrSymptom) {
        md += `- **Error Code / Symptom**: \`${item.errorCodeOrSymptom}\`\n`;
      }
      md += `- **Trigger Condition**: ${item.triggerCondition}\n`;
      md += `- **How to Unblock**: ${item.howToUnblock}\n`;
      md += `- **Workaround While Waiting**: ${item.workaroundWhilstWaiting}\n\n`;
    });
  }

  // 6. Composio SDK Snippets
  md += `## 6. Composio SDK Wiring & Code Snippets\n\n`;
  md += `- **Recommended Auth Scheme**: \`${guide.composioIntegration.recommendedScheme}\`\n`;
  md += `\n**Configuration Steps:**\n`;
  guide.composioIntegration.configurationSteps.value.forEach((step, i) => {
    md += `${i + 1}. ${step}\n`;
  });
  md += `\n`;

  guide.composioIntegration.sdkSnippets.forEach((snippet) => {
    const lang = snippet.language === "python" ? "python" : "typescript";
    md += `### Code Snippet (${snippet.language.toUpperCase()}) — \`[${snippet.validationStatus}]\`\n`;
    md += `> Note: ${snippet.validationNote}\n\n`;
    md += "```" + lang + "\n";
    md += snippet.code + "\n";
    md += "```\n\n";
  });

  return md;
}

export const ExportEngine: React.FC<ExportEngineProps> = ({ guide }) => {
  const [copiedType, setCopiedType] = useState<"md" | "json" | null>(null);

  const downloadFile = (content: string, filename: string, type: string) => {
    const blob = new Blob([content], { type });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleExportMarkdown = () => {
    const md = generateGuideMarkdown(guide);
    downloadFile(md, `${guide.appId}-oauth-readiness-runbook.md`, "text/markdown");
  };

  const handleExportJson = () => {
    const jsonStr = JSON.stringify(guide, null, 2);
    downloadFile(jsonStr, `${guide.appId}-integration-readiness.json`, "application/json");
  };

  const handleCopyMarkdown = () => {
    const md = generateGuideMarkdown(guide);
    navigator.clipboard.writeText(md);
    setCopiedType("md");
    setTimeout(() => setCopiedType(null), 2000);
  };

  const handleCopyJson = () => {
    const jsonStr = JSON.stringify(guide, null, 2);
    navigator.clipboard.writeText(jsonStr);
    setCopiedType("json");
    setTimeout(() => setCopiedType(null), 2000);
  };

  return (
    <div className="flex flex-wrap items-center gap-2.5">
      {/* Markdown Export Group */}
      <div className="inline-flex rounded-lg border border-slate-700 bg-slate-900/80 p-0.5">
        <button
          onClick={handleExportMarkdown}
          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium text-slate-200 hover:text-white hover:bg-slate-800 transition"
          title="Download formatted Markdown runbook"
        >
          <FileText className="w-3.5 h-3.5 text-cyan-400" />
          <span>Export Markdown</span>
          <Download className="w-3 h-3 text-slate-400 ml-0.5" />
        </button>
        <button
          onClick={handleCopyMarkdown}
          className="p-1.5 rounded-md text-slate-400 hover:text-slate-200 hover:bg-slate-800 transition"
          title="Copy Markdown to clipboard"
        >
          {copiedType === "md" ? (
            <Check className="w-3.5 h-3.5 text-emerald-400" />
          ) : (
            <Copy className="w-3.5 h-3.5" />
          )}
        </button>
      </div>

      {/* JSON Export Group */}
      <div className="inline-flex rounded-lg border border-slate-700 bg-slate-900/80 p-0.5">
        <button
          onClick={handleExportJson}
          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium text-slate-200 hover:text-white hover:bg-slate-800 transition"
          title="Download structured JSON guide"
        >
          <FileCode className="w-3.5 h-3.5 text-purple-400" />
          <span>Export JSON</span>
          <Download className="w-3 h-3 text-slate-400 ml-0.5" />
        </button>
        <button
          onClick={handleCopyJson}
          className="p-1.5 rounded-md text-slate-400 hover:text-slate-200 hover:bg-slate-800 transition"
          title="Copy JSON to clipboard"
        >
          {copiedType === "json" ? (
            <Check className="w-3.5 h-3.5 text-emerald-400" />
          ) : (
            <Copy className="w-3.5 h-3.5" />
          )}
        </button>
      </div>
    </div>
  );
};
export default ExportEngine;
